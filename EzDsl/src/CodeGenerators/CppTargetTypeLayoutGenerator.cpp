bool GenerateTargetTypeLayout(DiagnosticCollector *collector,
                              SymbolTable *table,
                              std::filesystem::path outPath,
                              std::string_view targetName,
                              TargetTypeLayoutGenWorkingMode mode)
{
    constexpr auto genName = "CodeGenerators::TargetTypeLayout";

    if (!collector)
    {
        return false;
    }

    if (!table)
    {
        collector->error(genName, "Cannot generate TargetTypeLayout with a null SymbolTable.");
        return false;
    }

    collector->trace(genName, "Generating target type layout in {}", outPath.string());

    // 1. Resolve Target Name
    std::string resolvedTargetName(targetName);
    if (resolvedTargetName.empty())
    {
        for (const Symbol *sym : table->getSymbols())
        {
            if (sym && sym->getType() == SymbolType::Target)
            {
                resolvedTargetName = sym->getName();
                break;
            }
        }
    }
    if (resolvedTargetName.empty())
    {
        resolvedTargetName = "Target";
    }
    resolvedTargetName = SanitizeIdentifier(resolvedTargetName);

    // 2. Ingest Types from SymbolTable
    std::vector<TypeEntry> types;
    size_t pointerSize = 8; // Default 64-bit

    for (const Symbol *sym : table->getSymbols())
    {
        if (!sym) continue;

        if (sym->getType() == SymbolType::Type)
        {
            const auto *data = sym->getIf<Sema::Symbols::TypeSymbol>();
            if (data)
            {
                types.push_back(TypeEntry{
                    .m_name = std::string(sym->getName()),
                    .m_bitSize = data->m_bitWidth,
                    .m_alignment = (data->m_bitWidth + 7) / 8
                });
            }
        }
    }

    // 3. Resolve Paths
    std::filesystem::path headerPath;
    std::filesystem::path sourcePath;
    std::string baseName = std::format("{}TypeLayout", resolvedTargetName);

    if (std::filesystem::is_directory(outPath) || !outPath.has_extension())
    {
        std::error_code ec;
        std::filesystem::create_directories(outPath, ec);
        if (ec)
        {
            collector->error(genName, "Failed to create directory {}: {}", outPath.string(), ec.message());
            return false;
        }
        headerPath = outPath / std::format("{}.h", baseName);
        sourcePath = outPath / std::format("{}.cpp", baseName);
    }
    else
    {
        if (outPath.has_parent_path())
        {
            std::error_code ec;
            std::filesystem::create_directories(outPath.parent_path(), ec);
        }
        headerPath = outPath;
        sourcePath = outPath;
        sourcePath.replace_extension(".cpp");
    }

    std::string headerFileName = headerPath.filename().string();

    if (mode & TargetTypeLayoutGenWorkingMode::Header)
    {
        std::ostringstream headerStream;
        EmitHeader(headerStream, resolvedTargetName, pointerSize);
        WriteFileIfChanged(headerPath, headerStream.str());
    }

    if (mode & TargetTypeLayoutGenWorkingMode::Source)
    {
        std::ostringstream sourceStream;
        EmitSource(sourceStream, resolvedTargetName, headerFileName, types, pointerSize);
        WriteFileIfChanged(sourcePath, sourceStream.str());
    }

    collector->trace(genName,
                     "Successfully synthesized target type layout into {}",
                     headerPath.filename().string());

    return true;
}

