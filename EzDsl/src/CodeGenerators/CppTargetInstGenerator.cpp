bool GenerateTargetInstructionDefs(DiagnosticCollector *collector,
                                   SymbolTable *table,
                                   std::filesystem::path outPath,
                                   std::string_view targetName,
                                   TargetInstGenWorkingMode mode)
{
    constexpr auto genName = "CodeGenerators::TargetInstructionDefs";

    if (!collector)
    {
        return false;
    }

    if (!table)
    {
        collector->error(genName, "Cannot generate TargetInstructionDefs with a null SymbolTable.");
        return false;
    }

    collector->trace(genName, "Generating target instruction definitions in {}", outPath.string());

    // 1. Resolve Target Name
    std::string resolvedTargetName(targetName);
    if (resolvedTargetName.empty())
    {
        for (const Symbol *sym : table->getSymbols())
        {
            if (sym && sym->getType() == SymbolType::Target)
            {
                resolvedTargetName = sym->getName();
                break;
            }
        }
    }
    if (resolvedTargetName.empty())
    {
        resolvedTargetName = "Target";
    }
    resolvedTargetName = SanitizeIdentifier(resolvedTargetName);

    // 2. Ingest Instructions & Formats
    std::vector<InstEntry> instructions;
    std::vector<FormatEntry> formats;

    for (const Symbol *sym : table->getSymbols())
    {
        if (!sym) continue;

        if (sym->getType() == SymbolType::Instruction)
        {
            const auto *data = sym->getIf<Sema::Symbols::TargetInstructionSymbol>();
            if (data)
            {
                InstEntry entry;
                entry.m_name = std::string(sym->getName());
                entry.m_symId = sym->getId();
                entry.m_formatId = data->m_formatId;
                entry.m_asmTemplate = std::string(data->m_asmTemplate);
                entry.m_latency = data->m_latency;
                entry.m_flagsMask = data->m_flagsMask;

                for (const auto &arg : data->m_args)
                {
                    entry.m_argNames.push_back(std::string(arg.m_name));
                    if (arg.m_dir == DSL::Ast::InstDef::InstOperandDir::ArgOut ||
                        arg.m_dir == DSL::Ast::InstDef::InstOperandDir::ArgInOut)
                    {
                        entry.m_numExplicitDefs++;
                    }
                    if (arg.m_dir == DSL::Ast::InstDef::InstOperandDir::ArgIn ||
                        arg.m_dir == DSL::Ast::InstDef::InstOperandDir::ArgInOut)
                    {
                        entry.m_numExplicitUses++;
                    }
                }

                for (const auto &imp : data->m_implicitArgs)
                {
                    entry.m_implicitArgNames.push_back(std::string(imp.m_name));
                    if (imp.m_dir == DSL::Ast::InstDef::InstOperandDir::ArgOut ||
                        imp.m_dir == DSL::Ast::InstDef::InstOperandDir::ArgInOut)
                    {
                        entry.m_numImplicitDefs++;
                    }
                    if (imp.m_dir == DSL::Ast::InstDef::InstOperandDir::ArgIn ||
                        imp.m_dir == DSL::Ast::InstDef::InstOperandDir::ArgInOut)
                    {
                        entry.m_numImplicitUses++;
                    }
                }

                instructions.push_back(std::move(entry));
            }
        }
        else if (sym->getType() == SymbolType::InstructionFormat)
        {
            const auto *data = sym->getIf<Sema::Symbols::InstructionFormatSymbol>();
            if (data)
            {
                formats.push_back(FormatEntry{
                    .m_name = std::string(sym->getName()),
                    .m_symId = sym->getId(),
                    .m_bitWidth = data->m_bitWidth
                });
            }
        }
    }

    // 3. Resolve Paths
    std::filesystem::path headerPath;
    std::filesystem::path sourcePath;
    std::filesystem::path encoderPath;

    std::string baseName = std::format("{}InstructionDefs", resolvedTargetName);
    std::string encoderBase = std::format("{}BinaryEncoder", resolvedTargetName);

    if (std::filesystem::is_directory(outPath) || !outPath.has_extension())
    {
        std::error_code ec;
        std::filesystem::create_directories(outPath, ec);
        if (ec)
        {
            collector->error(genName, "Failed to create directory {}: {}", outPath.string(), ec.message());
            return false;
        }
        headerPath = outPath / std::format("{}.h", baseName);
        sourcePath = outPath / std::format("{}.cpp", baseName);
        encoderPath = outPath / std::format("{}.cpp", encoderBase);
    }
    else
    {
        if (outPath.has_parent_path())
        {
            std::error_code ec;
            std::filesystem::create_directories(outPath.parent_path(), ec);
        }
        headerPath = outPath;
        sourcePath = outPath;
        sourcePath.replace_extension(".cpp");
        encoderPath = outPath.parent_path() / std::format("{}.cpp", encoderBase);
    }

    std::string headerFileName = headerPath.filename().string();

    // 4. Emit requested artifacts
    if (mode & TargetInstGenWorkingMode::Header)
    {
        std::ostringstream headerStream;
        EmitHeader(headerStream, resolvedTargetName, instructions);
        WriteFileIfChanged(headerPath, headerStream.str());
    }

    if (mode & TargetInstGenWorkingMode::Source)
    {
        std::ostringstream sourceStream;
        EmitSource(sourceStream, resolvedTargetName, headerFileName, instructions);
        WriteFileIfChanged(sourcePath, sourceStream.str());
    }

    if (mode & TargetInstGenWorkingMode::Encoder)
    {
        std::ostringstream encoderStream;
        EmitEncoder(encoderStream, resolvedTargetName, headerFileName, instructions);
        WriteFileIfChanged(encoderPath, encoderStream.str());
    }

    collector->trace(genName,
                     "Successfully synthesized {} target instructions and {} formats into {}",
                     instructions.size(),
                     formats.size(),
                     headerPath.filename().string());

    return true;
}

