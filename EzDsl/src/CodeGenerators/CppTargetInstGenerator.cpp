struct InstEntry
{
    std::string m_name;
    SymbolId m_symId{ InvalidSymbolId };
    SymbolId m_formatId{ InvalidSymbolId };
    std::string m_formatName;
    std::string m_asmTemplate;
    uint32_t m_latency{ 1 };
    uint32_t m_flagsMask{ 0 };
    std::vector<std::string> m_argNames;
    std::vector<std::string> m_implicitArgNames;
    size_t m_numExplicitDefs{ 0 };
    size_t m_numExplicitUses{ 0 };
    size_t m_numImplicitDefs{ 0 };
    size_t m_numImplicitUses{ 0 };
};

struct FormatEntry
{
    std::string m_name;
    SymbolId m_symId{ InvalidSymbolId };
    uint32_t m_bitWidth{ 32 };
};

void WriteFileIfChanged(const std::filesystem::path &filePath, const std::string &newContent)
{
    if (std::filesystem::exists(filePath))
    {
        std::ifstream currentFile(filePath, std::ios::in | std::ios::binary);
        if (currentFile.is_open())
        {
            std::ostringstream ss;
            ss << currentFile.rdbuf();
            if (ss.str() == newContent)
            {
                return;
            }
        }
    }

    std::ofstream outFile(filePath, std::ios::out | std::ios::trunc | std::ios::binary);
    if (outFile.is_open())
    {
        outFile << newContent;
    }
}

std::string SanitizeIdentifier(std::string_view name)
{
    if (name.empty())
    {
        return "Target";
    }

    std::string result;
    result.reserve(name.size());

    for (size_t i = 0; i < name.size(); ++i)
    {
        char c = name[i];
        if (std::isalnum(static_cast<unsigned char>(c)) || c == '_')
        {
            if (i == 0 && std::isdigit(static_cast<unsigned char>(c)))
            {
                result.push_back('_');
            }
            result.push_back(c);
        }
        else
        {
            result.push_back('_');
        }
    }

    return result;
}

std::string ToUpperString(std::string_view str)
{
    std::string result;
    result.reserve(str.size());
    for (char c : str)
    {
        result.push_back(static_cast<char>(std::toupper(static_cast<unsigned char>(c))));
    }
    return result;
}

void EmitHeader(std::ostream &out,
                std::string_view targetName,
                const std::vector<InstEntry> &instructions)
{
    std::string targetUpper = ToUpperString(targetName);

    out << std::format(R"(#ifndef EZDSL_{0}_INSTRUCTION_DEFS_H
#define EZDSL_{0}_INSTRUCTION_DEFS_H

// Auto-generated by EzDSL CppTargetInstGenerator. DO NOT EDIT.

#include "EzCoreCommon.h"
#include <cstdint>
#include <iosfwd>
#include <string_view>
#include <vector>

namespace {1}
{{

/**
 * Enumeration of all target hardware instruction opcodes for {1}.
 */
enum class TargetOpCode : uint16_t
{{
    TARGET_OPCODE_START = 1000,
)",
                       targetUpper,
                       targetName);

    for (const auto &inst : instructions)
    {
        out << std::format("    {},\n", inst.m_name);
    }

    out << std::format(R"(    TARGET_OPCODE_COUNT
}};

/**
 * Target instruction descriptor holding latency, behavioral flags, and operand properties.
 */
struct MirTargetInstructionDesc
{{
    const char *m_name;
    TargetOpCode m_opCode;
    uint32_t m_latency;
    uint32_t m_flags;
    size_t m_numExplicitDefs;
    size_t m_numExplicitUses;
    size_t m_numImplicitDefs;
    size_t m_numImplicitUses;
    const char *m_asmTemplate;
}};

/**
 * Retrieves the descriptor for the specified target instruction opcode.
 */
const MirTargetInstructionDesc &GetTargetInstructionDesc(TargetOpCode op);

/**
 * Returns the diagnostic string name of the target instruction opcode.
 */
const char *GetTargetOpCodeName(TargetOpCode op);

/**
 * Looks up a target instruction opcode by its name. Returns TargetOpCode::TARGET_OPCODE_START if not found.
 */
TargetOpCode GetTargetOpCodeByName(std::string_view name);

/**
 * Disassembles and prints the target instruction to an output stream using its declared assembly template.
 */
void PrintTargetInstruction(std::ostream &os, TargetOpCode op, const std::vector<std::string> &operands);

}} // namespace {1}

#endif // EZDSL_{0}_INSTRUCTION_DEFS_H
)",
                       targetUpper,
                       targetName);
}

void EmitSource(std::ostream &out,
                std::string_view targetName,
                std::string_view headerFileName,
                const std::vector<InstEntry> &instructions)
{
    out << std::format(R"(// Auto-generated by EzDSL CppTargetInstGenerator. DO NOT EDIT.

#include "{0}"
#include <algorithm>
#include <iostream>
#include <string>

namespace {1}
{{

static constexpr MirTargetInstructionDesc s_TargetInstructionDescs[] = {{
)",
                       headerFileName,
                       targetName);

    for (const auto &inst : instructions)
    {
        out << std::format("    {{ \"{0}\", TargetOpCode::{0}, {1}, {2}, {3}, {4}, {5}, {6}, \"{7}\" }},\n",
                           inst.m_name,
                           inst.m_latency,
                           inst.m_flagsMask,
                           inst.m_numExplicitDefs,
                           inst.m_numExplicitUses,
                           inst.m_numImplicitDefs,
                           inst.m_numImplicitUses,
                           inst.m_asmTemplate);
    }

    out << R"(};

static constexpr size_t TargetOpCount = sizeof(s_TargetInstructionDescs) / sizeof(s_TargetInstructionDescs[0]);

static const MirTargetInstructionDesc s_UnknownDesc = {
    "UNKNOWN", TargetOpCode::TARGET_OPCODE_START, 0, 0, 0, 0, 0, 0, ""
};

const MirTargetInstructionDesc &GetTargetInstructionDesc(TargetOpCode op)
{
    size_t rawVal = static_cast<size_t>(op);
    size_t startVal = static_cast<size_t>(TargetOpCode::TARGET_OPCODE_START);
    if (rawVal > startVal && rawVal <= startVal + TargetOpCount)
    {
        return s_TargetInstructionDescs[rawVal - startVal - 1];
    }
    return s_UnknownDesc;
}

const char *GetTargetOpCodeName(TargetOpCode op)
{
    return GetTargetInstructionDesc(op).m_name;
}

TargetOpCode GetTargetOpCodeByName(std::string_view name)
{
    for (size_t i = 0; i < TargetOpCount; ++i)
    {
        if (s_TargetInstructionDescs[i].m_name == name)
        {
            return s_TargetInstructionDescs[i].m_opCode;
        }
    }
    return TargetOpCode::TARGET_OPCODE_START;
}

void PrintTargetInstruction(std::ostream &os, TargetOpCode op, const std::vector<std::string> &operands)
{
    const auto &desc = GetTargetInstructionDesc(op);
    std::string tmpl(desc.m_asmTemplate);
    if (tmpl.empty())
    {
        os << desc.m_name;
        for (size_t i = 0; i < operands.size(); ++i)
        {
            os << (i == 0 ? " " : ", ") << operands[i];
        }
        return;
    }

    for (size_t i = 0; i < operands.size(); ++i)
    {
        std::string placeholder = "${" + std::to_string(i) + "}";
        size_t pos = 0;
        while ((pos = tmpl.find(placeholder, pos)) != std::string::npos)
        {
            tmpl.replace(pos, placeholder.length(), operands[i]);
            pos += operands[i].length();
        }
    }
    os << tmpl;
}

} // namespace )" << targetName << "\n";
}

void EmitEncoder(std::ostream &out,
                 std::string_view targetName,
                 std::string_view headerFileName,
                 const std::vector<InstEntry> &instructions)
{
    out << std::format(R"(// Auto-generated by EzDSL CppTargetInstGenerator. DO NOT EDIT.

#include "{0}"
#include "CodeSection.h"
#include <cstdint>
#include <vector>

namespace {1}
{{

)",
                       headerFileName,
                       targetName);

    for (const auto &inst : instructions)
    {
        out << std::format(R"(void Encode_{0}(CodeSection *sec, const std::vector<uint64_t> &operands)
{{
    if (!sec) return;
    (void)operands;
    // Default placeholder encoding logic for {0}
    sec->emit32(0x00000000);
}}

)",
                           inst.m_name);
    }

    out << std::format(R"(bool EncodeTargetInstruction(CodeSection *sec, TargetOpCode op, const std::vector<uint64_t> &operands)
{{
    if (!sec) return false;

    switch (op)
    {{
)",
                       targetName);

    for (const auto &inst : instructions)
    {
        out << std::format(R"(        case TargetOpCode::{0}:
            Encode_{0}(sec, operands);
            return true;
)",
                           inst.m_name);
    }

    out << R"(        default:
            return false;
    }
}

} // namespace )" << targetName << "\n";
}

