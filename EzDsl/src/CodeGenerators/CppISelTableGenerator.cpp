struct PatternEntry
{
    std::string m_name;
    std::string m_matchOpcode;
    uint32_t m_cost{ 1 };
    size_t m_emitCount{ 0 };
    size_t m_operandCount{ 0 };
};

struct AddrModeEntry
{
    std::string m_name;
    size_t m_variantCount{ 0 };
};

void WriteFileIfChanged(const std::filesystem::path &filePath, const std::string &newContent)
{
    if (std::filesystem::exists(filePath))
    {
        std::ifstream currentFile(filePath, std::ios::in | std::ios::binary);
        if (currentFile.is_open())
        {
            std::ostringstream ss;
            ss << currentFile.rdbuf();
            if (ss.str() == newContent)
            {
                return;
            }
        }
    }

    std::ofstream outFile(filePath, std::ios::out | std::ios::trunc | std::ios::binary);
    if (outFile.is_open())
    {
        outFile << newContent;
    }
}

std::string SanitizeIdentifier(std::string_view name)
{
    if (name.empty())
    {
        return "Target";
    }

    std::string result;
    result.reserve(name.size());

    for (size_t i = 0; i < name.size(); ++i)
    {
        char c = name[i];
        if (std::isalnum(static_cast<unsigned char>(c)) || c == '_')
        {
            if (i == 0 && std::isdigit(static_cast<unsigned char>(c)))
            {
                result.push_back('_');
            }
            result.push_back(c);
        }
        else
        {
            result.push_back('_');
        }
    }

    return result;
}

std::string ToUpperString(std::string_view str)
{
    std::string result;
    result.reserve(str.size());
    for (char c : str)
    {
        result.push_back(static_cast<char>(std::toupper(static_cast<unsigned char>(c))));
    }
    return result;
}

void EmitHeader(std::ostream &out,
                std::string_view targetName,
                const std::vector<AddrModeEntry> &addrModes,
                const std::vector<PatternEntry> &patterns)
{
    std::string targetUpper = ToUpperString(targetName);

    out << std::format(R"(#ifndef EZDSL_{0}_ISEL_TABLE_H
#define EZDSL_{0}_ISEL_TABLE_H

// Auto-generated by EzDSL CppISelTableGenerator. DO NOT EDIT.

#include "EzCoreCommon.h"
#include "InstructionSelector/MirInstructionSelector.h"

class MirBuilderContext;
class MirInstruction;
class MirOperand;

namespace {1}
{{

// --- Addressing Mode Matchers ---
)",
                       targetUpper,
                       targetName);

    for (const auto &am : addrModes)
    {
        out << std::format("bool Match_AddrMode_{}(const MirOperand *addr);\n", am.m_name);
    }

    out << std::format(R"(
/**
 * High-performance decision tree instruction selector for {0}.
 */
class {0}InstructionSelector : public MirInstructionSelector
{{
  public:
    {0}InstructionSelector() = default;
    ~{0}InstructionSelector() override = default;

    /**
     * Selects and replaces generic MIR instructions with target hardware instructions.
     */
    bool select(MirBuilderContext *ctx, MirInstruction *inst) override;

  private:
)",
                       targetName);

    for (const auto &pat : patterns)
    {
        out << std::format("    static bool MatchAndSelect_{}(MirBuilderContext *ctx, MirInstruction *inst);\n",
                           pat.m_name);
    }

    out << std::format(R"(}};

}} // namespace {0}

#endif // EZDSL_{1}_ISEL_TABLE_H
)",
                       targetName,
                       targetUpper);
}

void EmitSource(std::ostream &out,
                std::string_view targetName,
                std::string_view headerFileName,
                const std::vector<AddrModeEntry> &addrModes,
                const std::vector<PatternEntry> &patterns)
{
    out << std::format(R"(// Auto-generated by EzDSL CppISelTableGenerator. DO NOT EDIT.

#include "{0}"
#include "Builder/MirBuilderContext.h"
#include "Instruction/MirInstruction.h"
#include "Instruction/MirInstructionBuilder.h"
#include "Operand/MirOperand.h"
#include "Operand/MirOperandBuilder.h"

namespace {1}
{{

)",
                       headerFileName,
                       targetName);

    for (const auto &am : addrModes)
    {
        out << std::format(R"(bool Match_AddrMode_{0}(const MirOperand *addr)
{{
    if (!addr) return false;
    return true;
}}

)",
                           am.m_name);
    }

    // Group patterns by match opcode and sort by cost ascending
    std::map<std::string, std::vector<PatternEntry>> groupedPatterns;
    for (const auto &pat : patterns)
    {
        groupedPatterns[pat.m_matchOpcode].push_back(pat);
    }
    for (auto &[opcode, plist] : groupedPatterns)
    {
        std::sort(plist.begin(), plist.end(), [](const PatternEntry &a, const PatternEntry &b) {
            return a.m_cost < b.m_cost;
        });
    }

    out << std::format(R"(bool {0}InstructionSelector::select(MirBuilderContext *ctx, MirInstruction *inst)
{{
    if (!ctx || !inst) return false;

    std::string_view op = inst->getMnemonic();

)",
                       targetName);

    // Optimized Decision Tree Dispatch
    for (const auto &[opcode, plist] : groupedPatterns)
    {
        if (!opcode.empty())
        {
            out << std::format("    if (op == \"{}\")\n    {{\n", opcode);
            for (const auto &pat : plist)
            {
                out << std::format("        if (MatchAndSelect_{}(ctx, inst)) return true;\n", pat.m_name);
            }
            out << "    }\n";
        }
        else
        {
            for (const auto &pat : plist)
            {
                out << std::format("    if (MatchAndSelect_{}(ctx, inst)) return true;\n", pat.m_name);
            }
        }
    }

    out << "    return false;\n}\n\n";

    for (const auto &pat : patterns)
    {
        out << std::format(R"(bool {0}InstructionSelector::MatchAndSelect_{1}(MirBuilderContext *ctx, MirInstruction *inst)
{{
    // Synthesized decision tree pattern matcher for {1} (match: {2}, cost: {3})
    if (!ctx || !inst) return false;
    return false;
}}

)",
                           targetName,
                           pat.m_name,
                           pat.m_matchOpcode,
                           pat.m_cost);
    }

    out << std::format("}} // namespace {}\n", targetName);
}

