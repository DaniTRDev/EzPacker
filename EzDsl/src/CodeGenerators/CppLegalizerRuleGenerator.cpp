bool GenerateTargetLegalizerRules(DiagnosticCollector *collector,
                                  SymbolTable *table,
                                  std::filesystem::path outPath,
                                  std::string_view targetName,
                                  LegalizerRuleGenWorkingMode mode)
{
    constexpr auto genName = "CodeGenerators::TargetLegalizerRules";

    if (!collector)
    {
        return false;
    }

    if (!table)
    {
        collector->error(genName, "Cannot generate TargetLegalizerRules with a null SymbolTable.");
        return false;
    }

    collector->trace(genName, "Generating target legalize rules in {}", outPath.string());

    // 1. Resolve Target Name
    std::string resolvedTargetName(targetName);
    if (resolvedTargetName.empty())
    {
        for (const Symbol *sym : table->getSymbols())
        {
            if (sym && sym->getType() == SymbolType::Target)
            {
                resolvedTargetName = sym->getName();
                break;
            }
        }
    }
    if (resolvedTargetName.empty())
    {
        resolvedTargetName = "Target";
    }
    resolvedTargetName = SanitizeIdentifier(resolvedTargetName);

    // 2. Ingest Rewrite Rules from SymbolTable
    std::vector<RuleEntry> rules;

    for (const Symbol *sym : table->getSymbols())
    {
        if (!sym) continue;

        const auto *ruleData = sym->getIf<Sema::Symbols::LegalizeRewriteRuleSymbol>();
        if (ruleData)
        {
            RuleEntry entry;
            entry.m_name = std::string(ruleData->m_ruleName);
            entry.m_patternCount = ruleData->m_matchPatterns.size();
            entry.m_expansionCount = ruleData->m_expansionSequence.size();
            if (!ruleData->m_matchPatterns.empty())
            {
                entry.m_matchOpcode = std::string(ruleData->m_matchPatterns[0].m_opcode);
            }
            rules.push_back(std::move(entry));
        }
    }

    // 3. Resolve Paths
    std::filesystem::path headerPath;
    std::filesystem::path sourcePath;
    std::string baseName = std::format("{}LegalizeRules", resolvedTargetName);

    if (std::filesystem::is_directory(outPath) || !outPath.has_extension())
    {
        std::error_code ec;
        std::filesystem::create_directories(outPath, ec);
        if (ec)
        {
            collector->error(genName, "Failed to create directory {}: {}", outPath.string(), ec.message());
            return false;
        }
        headerPath = outPath / std::format("{}.h", baseName);
        sourcePath = outPath / std::format("{}.cpp", baseName);
    }
    else
    {
        if (outPath.has_parent_path())
        {
            std::error_code ec;
            std::filesystem::create_directories(outPath.parent_path(), ec);
        }
        headerPath = outPath;
        sourcePath = outPath;
        sourcePath.replace_extension(".cpp");
    }

    std::string headerFileName = headerPath.filename().string();

    if (mode & LegalizerRuleGenWorkingMode::Header)
    {
        std::ostringstream headerStream;
        EmitHeader(headerStream, resolvedTargetName, rules);
        WriteFileIfChanged(headerPath, headerStream.str());
    }

    if (mode & LegalizerRuleGenWorkingMode::Source)
    {
        std::ostringstream sourceStream;
        EmitSource(sourceStream, resolvedTargetName, headerFileName, rules);
        WriteFileIfChanged(sourcePath, sourceStream.str());
    }

    collector->trace(genName,
                     "Successfully synthesized {} rewrite rules into {}",
                     rules.size(),
                     headerPath.filename().string());

    return true;
}

