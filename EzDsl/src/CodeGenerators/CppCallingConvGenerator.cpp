struct CallingConvEntry
{
    std::string m_name;
    uint32_t m_stackAlign{ 16 };
    uint32_t m_shadowSpace{ 0 };
    bool m_growsDown{ true };
    bool m_calleeCleanup{ false };
};

void WriteFileIfChanged(const std::filesystem::path &filePath, const std::string &newContent)
{
    if (std::filesystem::exists(filePath))
    {
        std::ifstream currentFile(filePath, std::ios::in | std::ios::binary);
        if (currentFile.is_open())
        {
            std::ostringstream ss;
            ss << currentFile.rdbuf();
            if (ss.str() == newContent)
            {
                return;
            }
        }
    }

    std::ofstream outFile(filePath, std::ios::out | std::ios::trunc | std::ios::binary);
    if (outFile.is_open())
    {
        outFile << newContent;
    }
}

std::string SanitizeIdentifier(std::string_view name)
{
    if (name.empty())
    {
        return "Target";
    }

    std::string result;
    result.reserve(name.size());

    for (size_t i = 0; i < name.size(); ++i)
    {
        char c = name[i];
        if (std::isalnum(static_cast<unsigned char>(c)) || c == '_')
        {
            if (i == 0 && std::isdigit(static_cast<unsigned char>(c)))
            {
                result.push_back('_');
            }
            result.push_back(c);
        }
        else
        {
            result.push_back('_');
        }
    }

    return result;
}

std::string ToUpperString(std::string_view str)
{
    std::string result;
    result.reserve(str.size());
    for (char c : str)
    {
        result.push_back(static_cast<char>(std::toupper(static_cast<unsigned char>(c))));
    }
    return result;
}

void EmitHeader(std::ostream &out,
                std::string_view targetName,
                const std::vector<CallingConvEntry> &convs)
{
    std::string targetUpper = ToUpperString(targetName);

    out << std::format(R"(#ifndef EZDSL_{0}_CALLING_CONVENTIONS_H
#define EZDSL_{0}_CALLING_CONVENTIONS_H

// Auto-generated by EzDSL CppCallingConvGenerator. DO NOT EDIT.

#include "Function/CallingConvDesc.h"
#include <memory_resource>
#include <vector>

namespace {1}
{{

)",
                       targetUpper,
                       targetName);

    for (const auto &cc : convs)
    {
        out << std::format(R"(/**
 * Calling convention descriptor for {0}.
 */
class {0}_CallingConvDesc : public CallingConvDesc
{{
  public:
    explicit {0}_CallingConvDesc(std::pmr::memory_resource *alloc) :
        m_alloc(alloc),
        m_calleeSaved(alloc),
        m_callerSaved(alloc)
    {{}}

    ~{0}_CallingConvDesc() override = default;

    ArgumentLocationDesc getArgLoc(MirType *type, CallLoweringState *callState) override;
    ArgumentLocationDesc getReturnLoc(MirType *type, CallLoweringState *callState) override;
    bool canReturnInRegs(MirType *type) const override;
    bool isCalleeCleanup() const override;
    bool doesStackGrowsDownwards() const override;
    const char *getName() const override;
    MirRegisterRef getFramePointerReg() const override;
    MirRegisterRef getStackPointerReg() const override;
    size_t getStackAlignment() const override;
    size_t getShadowSpaceSize() const override;
    bool hasFramePointer(MirFunction *func) const override;
    void classify(MirType *type, std::pmr::vector<CallingConvTypeClass> &out) const override;
    const std::pmr::vector<MirRegisterRef> &getAllCalleeSavedRegs() override;
    const std::pmr::vector<MirRegisterRef> &getCalleeSavedRegs(MirRegisterClass *_class) override;
    const std::pmr::vector<MirRegisterRef> &getAllCallerSavedRegs() override;
    const std::pmr::vector<MirRegisterRef> &getCallerSavedRegs(MirRegisterClass *_class) override;

  private:
    std::pmr::memory_resource *m_alloc;
    std::pmr::vector<MirRegisterRef> m_calleeSaved;
    std::pmr::vector<MirRegisterRef> m_callerSaved;
}};

CallingConvDesc *Create_{0}(std::pmr::memory_resource *alloc);

)",
                           cc.m_name);
    }

    out << std::format(R"(/**
 * Factory function creating all available calling conventions for {0}.
 */
std::pmr::vector<CallingConvDesc *> CreateAllCallingConventions(std::pmr::memory_resource *alloc);

}} // namespace {0}

#endif // EZDSL_{1}_CALLING_CONVENTIONS_H
)",
                       targetName,
                       targetUpper);
}

