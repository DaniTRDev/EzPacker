bool GenerateTargetCallingConventions(DiagnosticCollector *collector,
                                      SymbolTable *table,
                                      std::filesystem::path outPath,
                                      std::string_view targetName,
                                      CallingConvGenWorkingMode mode)
{
    constexpr auto genName = "CodeGenerators::TargetCallingConventions";

    if (!collector)
    {
        return false;
    }

    if (!table)
    {
        collector->error(genName, "Cannot generate TargetCallingConventions with a null SymbolTable.");
        return false;
    }

    collector->trace(genName, "Generating target calling conventions in {}", outPath.string());

    // 1. Resolve Target Name
    std::string resolvedTargetName(targetName);
    if (resolvedTargetName.empty())
    {
        for (const Symbol *sym : table->getSymbols())
        {
            if (sym && sym->getType() == SymbolType::Target)
            {
                resolvedTargetName = sym->getName();
                break;
            }
        }
    }
    if (resolvedTargetName.empty())
    {
        resolvedTargetName = "Target";
    }
    resolvedTargetName = SanitizeIdentifier(resolvedTargetName);

    // 2. Ingest Calling Conventions
    std::vector<CallingConvEntry> convs;

    for (const Symbol *sym : table->getSymbols())
    {
        if (!sym) continue;

        if (sym->getType() == SymbolType::CallingConv)
        {
            const auto *data = sym->getIf<Sema::Symbols::CallingConvSymbol>();
            if (data)
            {
                CallingConvEntry entry;
                entry.m_name = std::string(sym->getName());
                entry.m_stackAlign = data->m_stackAlign;
                entry.m_shadowSpace = data->m_shadowSpace;
                entry.m_growsDown = (data->m_stackDirection == DSL::Ast::CallingConvDef::StackDirection::Down);
                entry.m_calleeCleanup = (data->m_stackCleanup == DSL::Ast::CallingConvDef::StackCleaner::Callee);
                convs.push_back(std::move(entry));
            }
        }
    }

    // 3. Resolve Paths
    std::filesystem::path headerPath;
    std::filesystem::path sourcePath;
    std::string baseName = std::format("{}CallingConventions", resolvedTargetName);

    if (std::filesystem::is_directory(outPath) || !outPath.has_extension())
    {
        std::error_code ec;
        std::filesystem::create_directories(outPath, ec);
        if (ec)
        {
            collector->error(genName, "Failed to create directory {}: {}", outPath.string(), ec.message());
            return false;
        }
        headerPath = outPath / std::format("{}.h", baseName);
        sourcePath = outPath / std::format("{}.cpp", baseName);
    }
    else
    {
        if (outPath.has_parent_path())
        {
            std::error_code ec;
            std::filesystem::create_directories(outPath.parent_path(), ec);
        }
        headerPath = outPath;
        sourcePath = outPath;
        sourcePath.replace_extension(".cpp");
    }

    std::string headerFileName = headerPath.filename().string();

    if (mode & CallingConvGenWorkingMode::Header)
    {
        std::ostringstream headerStream;
        EmitHeader(headerStream, resolvedTargetName, convs);
        WriteFileIfChanged(headerPath, headerStream.str());
    }

    if (mode & CallingConvGenWorkingMode::Source)
    {
        std::ostringstream sourceStream;
        EmitSource(sourceStream, resolvedTargetName, headerFileName, convs);
        WriteFileIfChanged(sourcePath, sourceStream.str());
    }

    collector->trace(genName,
                     "Successfully synthesized {} calling conventions into {}",
                     convs.size(),
                     headerPath.filename().string());

    return true;
}

