bool GenerateTargetLegalizerTable(DiagnosticCollector *collector,
                                  SymbolTable *table,
                                  std::filesystem::path outPath,
                                  std::string_view targetName,
                                  LegalizerGenWorkingMode mode)
{
    constexpr auto genName = "CodeGenerators::TargetLegalizerTable";

    if (!collector)
    {
        return false;
    }

    if (!table)
    {
        collector->error(genName, "Cannot generate TargetLegalizerTable with a null SymbolTable.");
        return false;
    }

    collector->trace(genName, "Generating target legalizer action table in {}", outPath.string());

    // 1. Resolve Target Name
    std::string resolvedTargetName(targetName);
    if (resolvedTargetName.empty())
    {
        for (const Symbol *sym : table->getSymbols())
        {
            if (sym && sym->getType() == SymbolType::Target)
            {
                resolvedTargetName = sym->getName();
                break;
            }
        }
    }
    if (resolvedTargetName.empty())
    {
        resolvedTargetName = "Target";
    }
    resolvedTargetName = SanitizeIdentifier(resolvedTargetName);

    // 2. Ingest Legalize Actions from SymbolTable
    std::vector<ActionEntry> actions;

    for (const Symbol *sym : table->getSymbols())
    {
        if (!sym) continue;

        if (sym->getType() == SymbolType::LegalizeAction)
        {
            const auto *data = sym->getIf<Sema::Symbols::LegalizeActionSymbol>();
            if (data)
            {
                ActionEntry action;
                action.m_opcode = std::string(data->m_genericOpcode);

                for (const auto &clause : data->m_clauses)
                {
                    ClauseEntry cEntry;
                    cEntry.m_kind = clause.m_kind;
                    if (clause.m_libcallSymbol.has_value())
                    {
                        cEntry.m_libcallSymbol = std::string(*clause.m_libcallSymbol);
                    }

                    for (const auto &tCons : clause.m_types)
                    {
                        const Symbol *typeSym = table->getSymById(tCons.m_typeId);
                        if (typeSym)
                        {
                            cEntry.m_typeNames.push_back(std::string(typeSym->getName()));
                            cEntry.m_slotIndices.push_back(tCons.m_operandIndex.value_or(0));
                        }
                    }
                    action.m_clauses.push_back(std::move(cEntry));
                }

                actions.push_back(std::move(action));
            }
        }
    }

    // 3. Resolve Paths
    std::filesystem::path headerPath;
    std::filesystem::path sourcePath;
    std::string baseName = std::format("{}LegalizerActionTable", resolvedTargetName);

    if (std::filesystem::is_directory(outPath) || !outPath.has_extension())
    {
        std::error_code ec;
        std::filesystem::create_directories(outPath, ec);
        if (ec)
        {
            collector->error(genName, "Failed to create directory {}: {}", outPath.string(), ec.message());
            return false;
        }
        headerPath = outPath / std::format("{}.h", baseName);
        sourcePath = outPath / std::format("{}.cpp", baseName);
    }
    else
    {
        if (outPath.has_parent_path())
        {
            std::error_code ec;
            std::filesystem::create_directories(outPath.parent_path(), ec);
        }
        headerPath = outPath;
        sourcePath = outPath;
        sourcePath.replace_extension(".cpp");
    }

    std::string headerFileName = headerPath.filename().string();

    if (mode & LegalizerGenWorkingMode::Header)
    {
        std::ostringstream headerStream;
        EmitHeader(headerStream, resolvedTargetName);
        WriteFileIfChanged(headerPath, headerStream.str());
    }

    if (mode & LegalizerGenWorkingMode::Source)
    {
        std::ostringstream sourceStream;
        EmitSource(sourceStream, resolvedTargetName, headerFileName, actions);
        WriteFileIfChanged(sourcePath, sourceStream.str());
    }

    collector->trace(genName,
                     "Successfully synthesized {} legalize action entries into {}",
                     actions.size(),
                     headerPath.filename().string());

    return true;
}

