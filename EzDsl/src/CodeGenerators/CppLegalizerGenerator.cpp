struct ClauseEntry
{
    DSL::Ast::LegalizeActionDef::LegalizeActionKind m_kind;
    std::vector<std::string> m_typeNames;
    std::vector<uint32_t> m_slotIndices;
    std::string m_targetType;
    std::string m_libcallSymbol;
};

struct ActionEntry
{
    std::string m_opcode;
    std::vector<ClauseEntry> m_clauses;
};

void WriteFileIfChanged(const std::filesystem::path &filePath, const std::string &newContent)
{
    if (std::filesystem::exists(filePath))
    {
        std::ifstream currentFile(filePath, std::ios::in | std::ios::binary);
        if (currentFile.is_open())
        {
            std::ostringstream ss;
            ss << currentFile.rdbuf();
            if (ss.str() == newContent)
            {
                return;
            }
        }
    }

    std::ofstream outFile(filePath, std::ios::out | std::ios::trunc | std::ios::binary);
    if (outFile.is_open())
    {
        outFile << newContent;
    }
}

std::string SanitizeIdentifier(std::string_view name)
{
    if (name.empty())
    {
        return "Target";
    }

    std::string result;
    result.reserve(name.size());

    for (size_t i = 0; i < name.size(); ++i)
    {
        char c = name[i];
        if (std::isalnum(static_cast<unsigned char>(c)) || c == '_')
        {
            if (i == 0 && std::isdigit(static_cast<unsigned char>(c)))
            {
                result.push_back('_');
            }
            result.push_back(c);
        }
        else
        {
            result.push_back('_');
        }
    }

    return result;
}

std::string ToUpperString(std::string_view str)
{
    std::string result;
    result.reserve(str.size());
    for (char c : str)
    {
        result.push_back(static_cast<char>(std::toupper(static_cast<unsigned char>(c))));
    }
    return result;
}

const char *GetActionKindName(DSL::Ast::LegalizeActionDef::LegalizeActionKind kind)
{
    switch (kind)
    {
        case DSL::Ast::LegalizeActionDef::LegalizeActionKind::Legal: return "LegalizeAction::Legal";
        case DSL::Ast::LegalizeActionDef::LegalizeActionKind::WidenScalar: return "LegalizeAction::WidenScalar";
        case DSL::Ast::LegalizeActionDef::LegalizeActionKind::NarrowScalar: return "LegalizeAction::NarrowScalar";
        case DSL::Ast::LegalizeActionDef::LegalizeActionKind::Libcall: return "LegalizeAction::Libcall";
        case DSL::Ast::LegalizeActionDef::LegalizeActionKind::Custom: return "LegalizeAction::Custom";
        case DSL::Ast::LegalizeActionDef::LegalizeActionKind::Bitcast: return "LegalizeAction::Bitcast";
        case DSL::Ast::LegalizeActionDef::LegalizeActionKind::Unsupported: return "LegalizeAction::Unsupported";
        default: return "LegalizeAction::Unsupported";
    }
}

