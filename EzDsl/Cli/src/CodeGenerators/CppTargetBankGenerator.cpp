bool GenerateTargetRegisterBanks(DiagnosticCollector *collector,
                                 SymbolTable *table,
                                 std::filesystem::path outPath,
                                 std::string_view targetName,
                                 TargetBankGenWorkingMode mode)
{
    constexpr auto genName = "CodeGenerators::TargetRegisterBanks";

    if (!collector)
    {
        return false;
    }

    if (!table)
    {
        collector->error(genName, "Cannot generate TargetRegisterBanks with a null SymbolTable.");
        return false;
    }

    collector->trace(genName, "Generating target register banks in {}", outPath.string());

    // 1. Resolve Target Name
    std::string resolvedTargetName(targetName);
    if (resolvedTargetName.empty())
    {
        for (const Symbol *sym : table->getSymbols())
        {
            if (sym && sym->getType() == SymbolType::Target)
            {
                resolvedTargetName = sym->getName();
                break;
            }
        }
    }

    if (resolvedTargetName.empty())
    {
        resolvedTargetName = "Target";
    }

    resolvedTargetName = SanitizeIdentifier(resolvedTargetName);

    // 2. Ingest Banks, Classes, and Registers from SymbolTable
    std::vector<BankEntry> banks;
    std::vector<ClassEntry> classes;
    std::vector<RegEntry> regs;

    std::unordered_map<SymbolId, size_t> bankSymIdToIndex;
    std::unordered_map<SymbolId, size_t> classSymIdToIndex;
    std::unordered_map<SymbolId, size_t> regSymIdToIndex;

    for (const Symbol *sym : table->getSymbols())
    {
        if (!sym)
        {
            continue;
        }

        if (sym->getType() == SymbolType::RegisterBank)
        {
            const auto *data = sym->getIf<Sema::Symbols::RegisterBankSymbol>();
            if (data)
            {
                bankSymIdToIndex[sym->getId()] = banks.size();
                banks.push_back(BankEntry{ .m_name = std::string(sym->getName()), .m_symId = sym->getId() });
            }
        }
        else if (sym->getType() == SymbolType::RegisterClass)
        {
            const auto *data = sym->getIf<Sema::Symbols::RegisterClassSymbol>();
            if (data)
            {
                classSymIdToIndex[sym->getId()] = classes.size();
                classes.push_back(ClassEntry{ .m_name = std::string(sym->getName()),
                                              .m_symId = sym->getId(),
                                              .m_bankId = data->m_bankId });
            }
        }
        else if (sym->getType() == SymbolType::Register)
        {
            const auto *data = sym->getIf<Sema::Symbols::RegisterSymbol>();
            if (data)
            {
                regSymIdToIndex[sym->getId()] = regs.size();
                regs.push_back(RegEntry{ .m_name = std::string(sym->getName()),
                                         .m_symId = sym->getId(),
                                         .m_parentId = data->m_parentId,
                                         .m_bitSize = data->m_bitSize,
                                         .m_bitOffset = data->m_bitOffset,
                                         .m_primaryClassId = data->m_primaryClassId });
            }
        }
    }

    // Link Bank -> Classes
    for (auto &cls : classes)
    {
        auto bIt = bankSymIdToIndex.find(cls.m_bankId);
        if (bIt != bankSymIdToIndex.end())
        {
            cls.m_bankName = banks[bIt->second].m_name;
            banks[bIt->second].m_classNames.push_back(cls.m_name);
        }
    }

    // Link Class -> Registers
    for (size_t i = 0; i < regs.size(); ++i)
    {
        auto &reg = regs[i];
        reg.m_enumIndex = i + 1; // 1-based index (0 is NoRegister)

        auto cIt = classSymIdToIndex.find(reg.m_primaryClassId);
        if (cIt != classSymIdToIndex.end())
        {
            reg.m_className = classes[cIt->second].m_name;
            reg.m_bankName = classes[cIt->second].m_bankName;
            classes[cIt->second].m_regNames.push_back(reg.m_name);
            classes[cIt->second].m_regEnumIndices.push_back(reg.m_enumIndex);
        }

        if (reg.m_parentId.has_value())
        {
            auto pIt = regSymIdToIndex.find(*reg.m_parentId);
            if (pIt != regSymIdToIndex.end())
            {
                reg.m_parentName = regs[pIt->second].m_name;
            }
        }
    }

    // 3. Compute Register Hierarchy, Roots, Offsets, and Ancestors
    for (auto &reg : regs)
    {
        SymbolId current = reg.m_symId;
        uint32_t totalOffset = 0;
        std::vector<size_t> ancestors;

        while (true)
        {
            auto it = regSymIdToIndex.find(current);
            if (it == regSymIdToIndex.end())
            {
                break;
            }

            const auto &currReg = regs[it->second];
            if (current != reg.m_symId)
            {
                ancestors.push_back(currReg.m_enumIndex);
            }

            if (!currReg.m_parentId.has_value())
            {
                reg.m_rootId = currReg.m_symId;
                reg.m_rootName = currReg.m_name;
                break;
            }

            totalOffset += currReg.m_bitOffset;
            current = *currReg.m_parentId;
        }

        reg.m_absOffset = totalOffset;
        reg.m_superRegs = ancestors;
    }

    // Compute Direct Children
    for (const auto &reg : regs)
    {
        if (reg.m_parentId.has_value())
        {
            auto pIt = regSymIdToIndex.find(*reg.m_parentId);
            if (pIt != regSymIdToIndex.end())
            {
                regs[pIt->second].m_directChildren.push_back(reg.m_enumIndex);
            }
        }
    }

    // Compute Sub-Registers (transitive descendants) via BFS
    for (auto &reg : regs)
    {
        std::queue<size_t> workList;
        for (size_t childIdx : reg.m_directChildren)
        {
            workList.push(childIdx);
        }

        while (!workList.empty())
        {
            size_t childIdx = workList.front();
            workList.pop();

            reg.m_subRegs.push_back(childIdx);
            for (size_t nextChild : regs[childIdx - 1].m_directChildren)
            {
                workList.push(nextChild);
            }
        }
    }

    // 4. Resolve Output File Paths
    std::filesystem::path headerPath;
    std::filesystem::path sourcePath;
    std::string baseName = std::format("{}RegisterBanks", resolvedTargetName);

    if (std::filesystem::is_directory(outPath) || !outPath.has_extension())
    {
        std::error_code ec;
        std::filesystem::create_directories(outPath, ec);
        if (ec)
        {
            collector->error(genName, "Failed to create directory {}: {}", outPath.string(), ec.message());
            return false;
        }
        headerPath = outPath / std::format("{}.h", baseName);
        sourcePath = outPath / std::format("{}.cpp", baseName);
    }
    else
    {
        if (outPath.has_parent_path())
        {
            std::error_code ec;
            std::filesystem::create_directories(outPath.parent_path(), ec);
            if (ec)
            {
                collector->error(genName,
                                 "Failed to create directory {}: {}",
                                 outPath.parent_path().string(),
                                 ec.message());
                return false;
            }
        }

        if (outPath.extension() == ".h" || outPath.extension() == ".hpp")
        {
            headerPath = outPath;
            sourcePath = outPath;
            sourcePath.replace_extension(".cpp");
        }
        else
        {
            sourcePath = outPath;
            headerPath = outPath;
            headerPath.replace_extension(".h");
        }
    }

    std::string headerFileName = headerPath.filename().string();

    // 5. Emit Header if requested
    if (mode & TargetBankGenWorkingMode::Header)
    {
        std::ostringstream headerStream;
        EmitHeader(headerStream, resolvedTargetName, banks, classes, regs);
        WriteFileIfChanged(headerPath, headerStream.str());
    }

    // 6. Emit Source if requested
    if (mode & TargetBankGenWorkingMode::Source)
    {
        std::ostringstream sourceStream;
        EmitSource(sourceStream, resolvedTargetName, headerFileName, banks, classes, regs);
        WriteFileIfChanged(sourcePath, sourceStream.str());
    }

    collector->trace(genName,
                     "Successfully synthesized {} registers across {} classes and {} banks into {}",
                     regs.size(),
                     classes.size(),
                     banks.size(),
                     headerPath.filename().string());

    return true;
}

