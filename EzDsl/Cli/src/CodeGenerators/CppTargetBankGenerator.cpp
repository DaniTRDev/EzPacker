/**
 * Metadata representation for a physical or sub-register during code generation.
 */
struct RegEntry
{
    std::string m_name;
    SymbolId m_symId{ InvalidSymbolId };
    std::optional<SymbolId> m_parentId;
    std::string m_parentName;
    uint32_t m_bitSize{ 0 };
    uint32_t m_bitOffset{ 0 };
    SymbolId m_primaryClassId{ InvalidSymbolId };
    std::string m_className;
    std::string m_bankName;

    size_t m_enumIndex{ 0 };
    SymbolId m_rootId{ InvalidSymbolId };
    std::string m_rootName;
    uint32_t m_absOffset{ 0 };

    std::vector<size_t> m_directChildren;
    std::vector<size_t> m_subRegs;
    std::vector<size_t> m_superRegs;
};

/**
 * Metadata representation for a register class during code generation.
 */
struct ClassEntry
{
    std::string m_name;
    SymbolId m_symId{ InvalidSymbolId };
    SymbolId m_bankId{ InvalidSymbolId };
    std::string m_bankName;
    std::vector<std::string> m_regNames;
    std::vector<size_t> m_regEnumIndices;
};

/**
 * Metadata representation for a hardware register bank during code generation.
 */
struct BankEntry
{
    std::string m_name;
    SymbolId m_symId{ InvalidSymbolId };
    std::vector<std::string> m_classNames;
};

/**
 * Writes newContent to filePath only if the file does not exist or its existing content differs.
 * Preserves file modification timestamps for unchanged content to prevent rebuild storms.
 */
void WriteFileIfChanged(const std::filesystem::path &filePath, const std::string &newContent)
{
    if (std::filesystem::exists(filePath))
    {
        std::ifstream currentFile(filePath, std::ios::in | std::ios::binary);
        if (currentFile.is_open())
        {
            std::ostringstream ss;
            ss << currentFile.rdbuf();
            if (ss.str() == newContent)
            {
                return;
            }
        }
    }

    std::ofstream outFile(filePath, std::ios::out | std::ios::trunc | std::ios::binary);
    if (outFile.is_open())
    {
        outFile << newContent;
    }
}

/**
 * Sanitizes an arbitrary identifier name to make it a valid C++ identifier / namespace.
 */
std::string SanitizeIdentifier(std::string_view name)
{
    if (name.empty())
    {
        return "Target";
    }

    std::string result;
    result.reserve(name.size());

    for (size_t i = 0; i < name.size(); ++i)
    {
        char c = name[i];
        if (std::isalnum(static_cast<unsigned char>(c)) || c == '_')
        {
            if (i == 0 && std::isdigit(static_cast<unsigned char>(c)))
            {
                result.push_back('_');
            }
            result.push_back(c);
        }
        else
        {
            result.push_back('_');
        }
    }

    return result;
}

/**
 * Converts a string to uppercase (for header inclusion guard generation).
 */
std::string ToUpperString(std::string_view str)
{
    std::string result;
    result.reserve(str.size());
    for (char c : str)
    {
        result.push_back(static_cast<char>(std::toupper(static_cast<unsigned char>(c))));
    }
    return result;
}

