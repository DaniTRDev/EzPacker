static const char builtin_stdarg_h[] =
  "#ifndef _EZPACKER_STDARG_H\n"
  "#define _EZPACKER_STDARG_H\n"
  "\n"
  "typedef struct {\n"
  "    unsigned int gp_offset;\n"
  "    unsigned int fp_offset;\n"
  "    void *overflow_arg_area;\n"
  "    void *reg_save_area;\n"
  "} __va_elem;\n"
  "\n"
  "typedef __va_elem va_list[1];\n"
  "\n"
  "#define va_start(ap, last) \\\n"
  "    do { *(ap) = *(__va_elem *)__va_area__; } while (0)\n"
  "\n"
  "#define va_end(ap) do { } while (0)\n"
  "\n"
  "#define va_copy(dest, src) ((dest)[0] = (src)[0])\n"
  "\n"
  "static inline void *__va_arg_mem(__va_elem *ap, int sz, int align) {\n"
  "    void *p = ap->overflow_arg_area;\n"
  "    if (align > 8)\n"
  "        p = (void *)(((unsigned long long)p + 15) / 16 * 16);\n"
  "    ap->overflow_arg_area = (void *)(((unsigned long long)p + sz + 7) / 8 * 8);\n"
  "    return p;\n"
  "}\n"
  "\n"
  "static inline void *__va_arg_gp(__va_elem *ap, int sz, int align) {\n"
  "    if (ap->gp_offset >= 48)\n"
  "        return __va_arg_mem(ap, sz, align);\n"
  "    void *r = (char *)ap->reg_save_area + ap->gp_offset;\n"
  "    ap->gp_offset += 8;\n"
  "    return r;\n"
  "}\n"
  "\n"
  "static inline void *__va_arg_fp(__va_elem *ap, int sz, int align) {\n"
  "    if (ap->fp_offset >= 112)\n"
  "        return __va_arg_mem(ap, sz, align);\n"
  "    void *r = (char *)ap->reg_save_area + ap->fp_offset;\n"
  "    ap->fp_offset += 8;\n"
  "    return r;\n"
  "}\n"
  "\n"
  "#define va_arg(ap, ty) \\\n"
  "    ({ \\\n"
  "        int __klass = __builtin_reg_class(ty); \\\n"
  "        *(ty *)(__klass == 0 ? __va_arg_gp(ap, sizeof(ty), _Alignof(ty)) : \\\n"
  "                __klass == 1 ? __va_arg_fp(ap, sizeof(ty), _Alignof(ty)) : \\\n"
  "                __va_arg_mem(ap, sizeof(ty), _Alignof(ty))); \\\n"
  "    })\n"
  "\n"
  "#define __GNUC_VA_LIST 1\n"
  "typedef va_list __gnuc_va_list;\n"
  "\n"
  "#endif\n";

static const BuiltinHeader chibicc_builtin_headers[] = {
  { "stdint.h", builtin_stdint_h },
  { "stddef.h", builtin_stddef_h },
  { "stdbool.h", builtin_stdbool_h },
  { "limits.h", builtin_limits_h },
  { "stdalign.h", builtin_stdalign_h },
  { "stdnoreturn.h", builtin_stdnoreturn_h },
  { "iso646.h", builtin_iso646_h },
  { "float.h", builtin_float_h },
  { "stdarg.h", builtin_stdarg_h },
};

static inline bool chibicc_is_builtin_header(const char *name) {
  for (size_t i = 0; i < sizeof(chibicc_builtin_headers) / sizeof(chibicc_builtin_headers[0]); i++) {
    if (strcmp(chibicc_builtin_headers[i].name, name) == 0)
      return true;
  }
  return false;
}

static inline const char *chibicc_get_builtin_header(const char *name) {
  for (size_t i = 0; i < sizeof(chibicc_builtin_headers) / sizeof(chibicc_builtin_headers[0]); i++) {
    if (strcmp(chibicc_builtin_headers[i].name, name) == 0)
      return chibicc_builtin_headers[i].content;
  }
  return NULL;
}

