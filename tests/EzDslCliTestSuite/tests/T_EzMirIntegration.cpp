// ============================================================================
// 5. CMake Integration Contract Simulation
// ============================================================================

TEST_F(EzMirIntegrationTest, CMakeTypeTableGenerationContract)
{
    // Simulates EzDslGenerateTypeTable(TARGET EzMir INPUT types.tyf OUTPUT_DIR ...)
    std::string err;
    auto opts = parseArgs({ "-i", m_typesPath.string(), "-o", m_testTempDir.string(), "--emit-type-table" }, err);
    ASSERT_TRUE(opts.has_value()) << "CLI argument parsing failed: " << err;

    auto result1 = runDriver(*opts);
    EXPECT_TRUE(result1.success);
    EXPECT_EQ(result1.generatedFiles.size(), 2);

    auto hPath = m_testTempDir / "MirTypeTable.h";
    auto sPath = m_testTempDir / "MirTypeTable.cpp";

    auto mtimeH1 = std::filesystem::last_write_time(hPath);
    auto mtimeS1 = std::filesystem::last_write_time(sPath);

    // Re-run should preserve timestamps (incremental build contract)
    auto result2 = runDriver(*opts);
    EXPECT_TRUE(result2.success);
    EXPECT_EQ(result2.unchangedFiles.size(), 2);
    EXPECT_EQ(result2.generatedFiles.size(), 0);

    auto mtimeH2 = std::filesystem::last_write_time(hPath);
    auto mtimeS2 = std::filesystem::last_write_time(sPath);

    EXPECT_EQ(mtimeH1, mtimeH2);
    EXPECT_EQ(mtimeS1, mtimeS2);
}

// Simulates the CMake instruction-defs generation contract, including timestamp preservation on re-run.
TEST_F(EzMirIntegrationTest, CMakeInstructionDefsGenerationContract)
{
    // Simulates EzDslGenMirInstructions(TARGET EzMir INPUT instructions.irdf OUTPUT_DIR ...)
    std::string err;
    auto opts =
            parseArgs({ "-i", m_instructionsPath.string(), "-o", m_testTempDir.string(), "--emit-instructions" }, err);
    ASSERT_TRUE(opts.has_value()) << "CLI argument parsing failed: " << err;

    auto result1 = runDriver(*opts);
    EXPECT_TRUE(result1.success);
    EXPECT_EQ(result1.generatedFiles.size(), 1);

    auto hPath = m_testTempDir / "MirInstructionSetDefs.h";
    auto mtime1 = std::filesystem::last_write_time(hPath);

    // Re-run should preserve timestamps (incremental build contract)
    auto result2 = runDriver(*opts);
    EXPECT_TRUE(result2.success);
    EXPECT_EQ(result2.unchangedFiles.size(), 1);
    EXPECT_EQ(result2.generatedFiles.size(), 0);

    auto mtime2 = std::filesystem::last_write_time(hPath);
    EXPECT_EQ(mtime1, mtime2);
}

