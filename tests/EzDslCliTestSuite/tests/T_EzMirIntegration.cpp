// 7. CLI Subprocess End-to-End Execution
// ============================================================================

TEST_F(EzMirIntegrationTest, RunEzDslCliSubprocessOnEzMir)
{
    auto exe = findEzDslCliExe();
    if (exe.empty())
    {
        GTEST_SKIP() << "EzDslCli executable not found; skipping subprocess execution test.";
    }

    // 1. Process types.tyf
    std::string typesOutDir = (m_testTempDir / "proc_types").string();
    std::string stdOutTypes;
    int codeTypes = runCliProcess({ "-i", m_typesPath.string(), "-o", typesOutDir, "--emit-type-table" }, stdOutTypes);
    EXPECT_EQ(codeTypes, 0) << "CLI failed with output:\n" << stdOutTypes;
    EXPECT_TRUE(std::filesystem::exists(std::filesystem::path(typesOutDir) / "MirTypeTable.h"));
    EXPECT_TRUE(std::filesystem::exists(std::filesystem::path(typesOutDir) / "MirTypeTable.cpp"));

    // 2. Process instructions.irdf
    std::string instOutDir = (m_testTempDir / "proc_inst").string();
    std::string stdOutInst;
    int codeInst =
            runCliProcess({ "-i", m_instructionsPath.string(), "-o", instOutDir, "--emit-instructions" }, stdOutInst);
    EXPECT_EQ(codeInst, 0) << "CLI failed with output:\n" << stdOutInst;
    EXPECT_TRUE(std::filesystem::exists(std::filesystem::path(instOutDir) / "MirInstructionSetDefs.h"));
}
