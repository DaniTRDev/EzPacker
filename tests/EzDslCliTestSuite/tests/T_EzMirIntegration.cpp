// 3. Full Generation & Header/Source Content Verification for EzMir Types
// ============================================================================

TEST_F(EzMirIntegrationTest, GenerateAndVerifyEzMirTypeTable)
{
    CliOptions opts;
    opts.inputFilePath = m_typesPath.string();
    opts.outputPath = m_testTempDir.string();

    auto result = runDriver(opts);
    ASSERT_TRUE(result.success) << "Type table generation failed: " << result.errorMessage;

    auto headerPath = m_testTempDir / "MirTypeTable.h";
    auto sourcePath = m_testTempDir / "MirTypeTable.cpp";

    ASSERT_TRUE(std::filesystem::exists(headerPath));
    ASSERT_TRUE(std::filesystem::exists(sourcePath));

    std::string hContent = readFileContent(headerPath);
    std::string sContent = readFileContent(sourcePath);

    // --- Header File Verification ---
    // 1. Include Guards & Banner
    EXPECT_TRUE(hContent.find("#ifndef EZMIR_MIR_TYPE_TABLE_H") != std::string::npos);
    EXPECT_TRUE(hContent.find("#define EZMIR_MIR_TYPE_TABLE_H") != std::string::npos);
    EXPECT_TRUE(hContent.find("Auto-generated by EzDSL CppMirTypeTableGenerator") != std::string::npos);
    EXPECT_TRUE(hContent.find("#include \"Type/MirType.h\"") != std::string::npos);

    // 2. Compact ID Enum values matching EzMir types.tyf
    EXPECT_TRUE(hContent.find("enum class MirTypeCompactId : uint8_t") != std::string::npos);
    EXPECT_TRUE(hContent.find("Invalid = 0,") != std::string::npos);
    EXPECT_TRUE(hContent.find("_void = 1,") != std::string::npos);
    EXPECT_TRUE(hContent.find("__bindToken = 2,") != std::string::npos);
    EXPECT_TRUE(hContent.find("i1 = 4,") != std::string::npos);
    EXPECT_TRUE(hContent.find("i8 = 5,") != std::string::npos);
    EXPECT_TRUE(hContent.find("i16 = 6,") != std::string::npos);
    EXPECT_TRUE(hContent.find("i32 = 7,") != std::string::npos);
    EXPECT_TRUE(hContent.find("i64 = 8,") != std::string::npos);
    EXPECT_TRUE(hContent.find("i128 = 9,") != std::string::npos);
    EXPECT_TRUE(hContent.find("i256 = 10,") != std::string::npos);
    EXPECT_TRUE(hContent.find("f32 = 11,") != std::string::npos);
    EXPECT_TRUE(hContent.find("f64 = 12,") != std::string::npos);
    EXPECT_TRUE(hContent.find("f128 = 13,") != std::string::npos);
    EXPECT_TRUE(hContent.find("Custom = 255") != std::string::npos);

    // ptr is pointer type, must NOT have a compact ID
    EXPECT_TRUE(hContent.find("ptr =") == std::string::npos);

    // 3. MachineTypeCount (12 primitive types)
    EXPECT_TRUE(hContent.find("constexpr size_t MachineTypeCount = 12;") != std::string::npos);

    // 4. MirTypeTable Class Declarations & Accessor Methods
    EXPECT_TRUE(hContent.find("class MirTypeTable") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *i1();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *i8();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *i16();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *i32();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *i64();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *i128();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *i256();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *f32();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *f64();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *f128();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *_void();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *__bindToken();") != std::string::npos);

    // 5. Member pointers & lifecycle
    EXPECT_TRUE(hContent.find("MirType *m_i32Type{ nullptr };") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *m_f64Type{ nullptr };") != std::string::npos);
    EXPECT_TRUE(hContent.find("void initialize(size_t pointerBitWidth);") != std::string::npos);

    // --- Source File Verification ---
    EXPECT_TRUE(
            sContent.find(
                    "MirTypeTable::MirTypeTable(std::pmr::memory_resource *globalArena, size_t pointerBitWidth) :") !=
            std::string::npos);
    EXPECT_TRUE(sContent.find("m_compactIdToType.fill(nullptr);") != std::string::npos);
    EXPECT_TRUE(sContent.find("MirType *MirTypeTable::i32() { return m_i32Type; }") != std::string::npos);
    EXPECT_TRUE(sContent.find("MirType *MirTypeTable::f64() { return m_f64Type; }") != std::string::npos);
    // Initialization checks
    EXPECT_TRUE(sContent.find("m_i1Type = create(MirTypeKind::Integer, 1, 1, {}, \"i1\", 4);") != std::string::npos);
    EXPECT_TRUE(sContent.find("m_i32Type = create(MirTypeKind::Integer, 32, 32, {}, \"i32\", 7);") !=
                std::string::npos);
    EXPECT_TRUE(sContent.find("m_i64Type = create(MirTypeKind::Integer, 64, 64, {}, \"i64\", 8);") !=
                std::string::npos);
    EXPECT_TRUE(sContent.find("m_f32Type = create(MirTypeKind::FloatingPoint, 32, 32, {}, \"f32\", 11);") !=
                std::string::npos);
    EXPECT_TRUE(sContent.find("m_f64Type = create(MirTypeKind::FloatingPoint, 64, 64, {}, \"f64\", 12);") !=
                std::string::npos);
    EXPECT_TRUE(sContent.find("m__voidType = create(MirTypeKind::Void, 0, 0, {}, \"_void\", 1);") != std::string::npos);
    EXPECT_TRUE(sContent.find("m___bindTokenType = create(MirTypeKind::BindingToken, 0, 0, {}, \"__bindToken\", 2);") !=
                std::string::npos);
}

