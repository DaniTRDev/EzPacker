// ============================================================================

TEST_F(CppMirInstructionGeneratorTest, TestConvenienceFunctionAndMtimePreservation)
{
    using namespace DSL::Ast::IrInstDef;
    declareRawInstruction("InstA", IrInstCategory::Arithmetic, IrInstTier::HighLevel, IrInstFlag::None);

    auto outHeader = m_testTempDir / "Defs.h";

    // Run via convenience function
    EXPECT_TRUE(GenerateMirIrInstructionDefs(getDiagCollector(), getSymbolTable(), outHeader));
    EXPECT_TRUE(std::filesystem::exists(outHeader));

    auto pastTime = std::filesystem::last_write_time(outHeader) - std::chrono::seconds(5);
    std::filesystem::last_write_time(outHeader, pastTime);
    auto mtime1 = std::filesystem::last_write_time(outHeader);

    // Running again with identical symbols should preserve mtime
    EXPECT_TRUE(GenerateMirIrInstructionDefs(getDiagCollector(), getSymbolTable(), outHeader));
    auto mtime2 = std::filesystem::last_write_time(outHeader);
    EXPECT_EQ(mtime1, mtime2);
}

