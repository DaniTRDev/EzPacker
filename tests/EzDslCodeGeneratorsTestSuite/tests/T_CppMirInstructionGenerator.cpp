// Verifies type symbols in the table are not emitted as instructions.
TEST_F(CppMirInstructionGeneratorTest, TestIgnoresNonInstructionSymbols)
{
    // Declare type symbols into the table
    registerType("i32", DSL::Ast::TypeDef::TypeKind::Integer, 32, 32, 1);
    registerType("f64", DSL::Ast::TypeDef::TypeKind::FloatingPoint, 64, 64, 2);

    auto outHeader = m_testTempDir / "NonInstDefs.h";
    CppMirInstructionGenerator generator(getDiagCollector(), getSymbolTable(), outHeader);
    EXPECT_TRUE(generator.run());

    std::string content = readFileContent(outHeader);
    // Ensure type symbols were not generated as instructions
    EXPECT_TRUE(content.find("INSTRUCTION(i32") == std::string::npos);
    EXPECT_TRUE(content.find("INSTRUCTION(f64") == std::string::npos);
}

