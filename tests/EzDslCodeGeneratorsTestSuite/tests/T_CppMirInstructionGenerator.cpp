// 1. Positive Integration Tests (Via DSL Parsing & Pass)
// ============================================================================

TEST_F(CppMirInstructionGeneratorTest, TestStandardInstructionSetGeneration)
{
    std::string irSource = R"(
        ir_inst Add ( Register:dst OUT, Register:lhs IN, Register:rhs IN ) {
            CATEGORY(Arithmetic);
            TIER(HighLevel);
            FLAGS(IsCommutative, SizeMatch);
        };

        ir_inst Nop () {
            CATEGORY(System);
            TIER(HighLevel);
        };

        ir_inst Branch ( AddressSource:target IN ) {
            CATEGORY(ControlFlow);
            TIER(HighLevel);
            FLAGS(IsBranch, IsTerminator);
        };

        ir_inst Ret () {
            CATEGORY(ControlFlow);
            TIER(HighLevel);
            FLAGS(IsReturn, IsTerminator);
        };
    )";

    ASSERT_TRUE(parseAndRunPass(irSource));

    auto outHeader = m_testTempDir / "MirInstructionSetDefs.h";
    CppMirInstructionGenerator generator(getDiagCollector(), getSymbolTable(), outHeader);
    ASSERT_TRUE(generator.run());
    ASSERT_TRUE(std::filesystem::exists(outHeader));

    std::string content = readFileContent(outHeader);

    // 1. Banner and guards
    EXPECT_TRUE(content.find("Auto-generated by EzDSL CppMirInstructionGenerator") != std::string::npos);
    EXPECT_TRUE(content.find("#ifdef INSTRUCTION") != std::string::npos);
    EXPECT_TRUE(content.find("#define OPERAND_CONSTRAINTS(...)") != std::string::npos);

    // 2. gtest collision protection
    EXPECT_TRUE(content.find("#ifdef TEST") != std::string::npos);
    EXPECT_TRUE(content.find("#pragma push_macro(\"TEST\")") != std::string::npos);
    EXPECT_TRUE(content.find("#pragma pop_macro(\"TEST\")") != std::string::npos);

    // 3. INVALID instruction
    EXPECT_TRUE(content.find("INSTRUCTION(INVALID, T(HighLevel), MirCat_Invalid, OPERAND_CONSTRAINTS(), F(None))") !=
                std::string::npos);

    // 4. Zero-operand instruction (Nop)
    EXPECT_TRUE(content.find("INSTRUCTION(Nop, T(HighLevel), MirCat_System, OPERAND_CONSTRAINTS(), F(None))") !=
                std::string::npos);

    // 5. Single-operand instruction (Branch)
    EXPECT_TRUE(content.find("INSTRUCTION(Branch,") != std::string::npos);
    EXPECT_TRUE(content.find("MirCat_ControlFlow") != std::string::npos);
    EXPECT_TRUE(content.find("OPERAND_CONSTRAINTS({ ExpectedOperandType::AddressSource, MirOperandFlag::Read })") !=
                std::string::npos);
    EXPECT_TRUE(content.find("F(IsTerminator) | F(IsBranch)") != std::string::npos);

    // 6. Three-operand ALU instruction (Add)
    EXPECT_TRUE(content.find("INSTRUCTION(Add,") != std::string::npos);
    EXPECT_TRUE(content.find("MirCat_Arithmetic") != std::string::npos);
    EXPECT_TRUE(content.find("{ ExpectedOperandType::Register, MirOperandFlag::Write }") != std::string::npos);
    EXPECT_TRUE(content.find("{ ExpectedOperandType::Register, MirOperandFlag::Read }") != std::string::npos);
    EXPECT_TRUE(content.find("F(SizeMatch) | F(IsCommutative)") != std::string::npos);

    // 7. Undef cleanup
    EXPECT_TRUE(content.find("#undef T") != std::string::npos);
    EXPECT_TRUE(content.find("#undef F") != std::string::npos);
    EXPECT_TRUE(content.find("#undef OPERAND_CONSTRAINTS") != std::string::npos);
    EXPECT_TRUE(content.find("#endif // INSTRUCTION") != std::string::npos);
}

