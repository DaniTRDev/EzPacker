TEST_F(CppMirTypeTableGeneratorTest, TestIgnoresNonTypeSymbols)
{
    // Register an instruction symbol into the table
    Symbols::IrInstructionSymbol instSym{ .m_name = "DummyInst",
                                          .m_category = DSL::Ast::IrInstDef::IrInstCategory::System,
                                          .m_tier = DSL::Ast::IrInstDef::IrInstTier::HighLevel,
                                          .m_flags = DSL::Ast::IrInstDef::IrInstFlag::None };
    getSymbolTable()->declareSym(nullptr, SymbolType::IrInstruction, std::move(instSym), "DummyInst");

    CppMirTypeTableGenerator generator(getDiagCollector(), getSymbolTable(), m_testTempDir);
    EXPECT_TRUE(generator.run());

    std::string hContent = readFileContent(m_testTempDir / "MirTypeTable.h");
    EXPECT_TRUE(hContent.find("DummyInst") == std::string::npos);
}

