class CppMirTypeTableGeneratorTest : public EzDslCodeGeneratorsTestSuiteAsGtest
{
  protected:
    bool parseAndRunPass(const std::string &source)
    {
        auto ast = parseTypeDefFile(source);
        if (!ast.has_value())
        {
            return false;
        }

        TypePass typePass;
        return typePass.run(getDiagCollector(), getSymbolTable(), &ast.value());
    }
};

// ============================================================================
// 1. Positive Integration Tests (Via DSL Parsing & Pass)
// ============================================================================

TEST_F(CppMirTypeTableGeneratorTest, TestStandardTypeTableGenerationViaDsl)
{
    std::string typeSource = R"(
        integer i1(1);
        integer i8(8);
        integer i32(32);
        float f32(32);
        float f64(64);
        void v();
        pointer ptr();
    )";

    ASSERT_TRUE(parseAndRunPass(typeSource));

    CppMirTypeTableGenerator generator(getDiagCollector(), getSymbolTable(), m_testTempDir);
    ASSERT_TRUE(generator.run());

    auto headerPath = m_testTempDir / "MirTypeTable.h";
    auto sourcePath = m_testTempDir / "MirTypeTable.cpp";

    ASSERT_TRUE(std::filesystem::exists(headerPath));
    ASSERT_TRUE(std::filesystem::exists(sourcePath));

    // --- Verify Header Content ---
    std::string hContent = readFileContent(headerPath);

    // 1. Guards, Banners, Includes
    EXPECT_TRUE(hContent.find("#ifndef EZMIR_MIR_TYPE_TABLE_H") != std::string::npos);
    EXPECT_TRUE(hContent.find("#define EZMIR_MIR_TYPE_TABLE_H") != std::string::npos);
    EXPECT_TRUE(hContent.find("Auto-generated by EzDSL CppMirTypeTableGenerator") != std::string::npos);
    EXPECT_TRUE(hContent.find("#include \"Type/MirType.h\"") != std::string::npos);

    // 2. MirTypeCompactId Enum (excludes ptr)
    EXPECT_TRUE(hContent.find("enum class MirTypeCompactId : uint8_t") != std::string::npos);
    EXPECT_TRUE(hContent.find("Invalid = 0,") != std::string::npos);
    EXPECT_TRUE(hContent.find("i1 = 1,") != std::string::npos);
    EXPECT_TRUE(hContent.find("i8 = 2,") != std::string::npos);
    EXPECT_TRUE(hContent.find("i32 = 3,") != std::string::npos);
    EXPECT_TRUE(hContent.find("f32 = 4,") != std::string::npos);
    EXPECT_TRUE(hContent.find("f64 = 5,") != std::string::npos);
    EXPECT_TRUE(hContent.find("v = 6,") != std::string::npos);
    EXPECT_TRUE(hContent.find("Custom = 255") != std::string::npos);
    EXPECT_TRUE(hContent.find("ptr =") == std::string::npos);

    // 3. MachineTypeCount (6 primitive types, excluding ptr)
    EXPECT_TRUE(hContent.find("constexpr size_t MachineTypeCount = 6;") != std::string::npos);

    // 4. MirTypeTable Class Declarations & Accessors
    EXPECT_TRUE(hContent.find("class MirTypeTable") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *i32();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *f64();") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *m_i32Type{ nullptr };") != std::string::npos);
    EXPECT_TRUE(hContent.find("MirType *m_f64Type{ nullptr };") != std::string::npos);
    EXPECT_TRUE(hContent.find("void initialize(size_t pointerBitWidth);") != std::string::npos);

    // --- Verify Source Content ---
    std::string sContent = readFileContent(sourcePath);

    EXPECT_TRUE(sContent.find("MirTypeTable::MirTypeTable(std::pmr::memory_resource *globalArena, size_t pointerBitWidth) :") !=
                std::string::npos);
    EXPECT_TRUE(sContent.find("m_compactIdToType.fill(nullptr);") != std::string::npos);
    EXPECT_TRUE(sContent.find("MirType *MirTypeTable::create(") != std::string::npos);
    EXPECT_TRUE(sContent.find("MirType *MirTypeTable::getFuncType(") != std::string::npos);
    EXPECT_TRUE(sContent.find("MirType *MirTypeTable::getPtr(MirType *srcType)") != std::string::npos);
    EXPECT_TRUE(sContent.find("MirType *MirTypeTable::getArray(MirType *elementType, size_t elementCount)") !=
                std::string::npos);
    EXPECT_TRUE(sContent.find("MirType *MirTypeTable::getFloatingTypeBySize(size_t sizeInBits) const") !=
                std::string::npos);
    EXPECT_TRUE(sContent.find("MirType *MirTypeTable::getIntegerTypeBySize(size_t sizeInBits) const") !=
                std::string::npos);
    EXPECT_TRUE(sContent.find("MirType *MirTypeTable::i32() { return m_i32Type; }") != std::string::npos);
    EXPECT_TRUE(sContent.find("void MirTypeTable::initialize(size_t pointerBitWidth)") != std::string::npos);
    EXPECT_TRUE(sContent.find("m_i32Type = create(MirTypeKind::Integer, 32, 32, {}, \"i32\", 3);") != std::string::npos);
    EXPECT_TRUE(sContent.find("m_f64Type = create(MirTypeKind::FloatingPoint, 64, 64, {}, \"f64\", 5);") !=
                std::string::npos);
}

// ============================================================================
// 2. Working Modes (Header-only, Source-only, Full) & Bitwise Operators
// ============================================================================

TEST_F(CppMirTypeTableGeneratorTest, TestWorkingModes)
{
    registerType("i32", DSL::Ast::TypeDef::TypeKind::Integer, 32, 32, 1);

    // 1. Bitwise operator assertions
    auto fullMode = MirTypeTableGenWorkingMode::Header | MirTypeTableGenWorkingMode::Source;
    EXPECT_EQ(fullMode, MirTypeTableGenWorkingMode::Full);
    EXPECT_TRUE(fullMode & MirTypeTableGenWorkingMode::Header);
    EXPECT_TRUE(fullMode & MirTypeTableGenWorkingMode::Source);

    // 2. Header-only generation
    auto headerOnlyDir = m_testTempDir / "header_only";
    std::filesystem::create_directories(headerOnlyDir);
    CppMirTypeTableGenerator genHeaderOnly(getDiagCollector(),
                                          getSymbolTable(),
                                          headerOnlyDir,
                                          MirTypeTableGenWorkingMode::Header);
    EXPECT_TRUE(genHeaderOnly.run());
    EXPECT_TRUE(std::filesystem::exists(headerOnlyDir / "MirTypeTable.h"));
    EXPECT_FALSE(std::filesystem::exists(headerOnlyDir / "MirTypeTable.cpp"));

    // 3. Source-only generation
    auto sourceOnlyDir = m_testTempDir / "source_only";
    std::filesystem::create_directories(sourceOnlyDir);
    CppMirTypeTableGenerator genSourceOnly(getDiagCollector(),
                                          getSymbolTable(),
                                          sourceOnlyDir,
                                          MirTypeTableGenWorkingMode::Source);
    EXPECT_TRUE(genSourceOnly.run());
    EXPECT_FALSE(std::filesystem::exists(sourceOnlyDir / "MirTypeTable.h"));
    EXPECT_TRUE(std::filesystem::exists(sourceOnlyDir / "MirTypeTable.cpp"));
}

